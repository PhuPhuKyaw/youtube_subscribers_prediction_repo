import streamlit as st
import pickle
import pandas as pd

st.markdown("""
<style>
.stApp {
    background-color: #F4FBF7;
}

[data-testid="stSidebar"] {
    background-color: #E3F4EA;
}
</style>
""", unsafe_allow_html=True)

df=pd.read_csv('youtube_channel_subscribers.csv')
df.columns=df.columns.str.strip()


def load_model():
    with open('subscriber_prediction.pkl','rb') as f:
        return pickle.load(f)


st.header(":streamlit: YouTube Channel Subscriber Estimator:")
"""  Explore how different channel characteristics relate to subscriber counts"""

st.info(
    """
:warning: Disclaimer: This is an estimated subscriber count generated by a machine learning model. Actual channel growth may vary depending on 
content quality, audience engagement, consistency, and other factors. Use this prediction as a reference, not a guarantee!
    """
)
with st.sidebar:
    st.image('parami.jpg')
    st.text("Student Name: Phu Phu Kyaw")
    st.text("Student ID: PIUS20240078")
    st.text("Class of 2028")

with st.form('subscriber_prediction'):
    col1,col2=st.columns(2)
    with col1:

        var1=st.slider("Enter monthly views",
                            max_value=df['Monthly_Views'].max(),
                            min_value=df['Monthly_Views'].min(), step = 10000)
        
        var2=st.slider("Enter total videos",
                    max_value=df['Total_Videos'].max(),
                    min_value=df['Total_Videos'].min(), step = 10)
        
        var3=st.slider("Enter average spend per video in USD",
                        max_value=df['Avg_Spend_Per_Video_USD'].max(),
                        min_value=df['Avg_Spend_Per_Video_USD'].min(), step = 1000.0)
        var4=st.number_input("Enter no of team members",
                                max_value=int(df['Team_Members'].max()),
                                min_value=int(df['Team_Members'].min()),
                                value=1)

        var5=st.slider("Enter average video length in minute",
                    max_value=df['Avg_Video_Length_Min'].max(),
                    min_value=df['Avg_Video_Length_Min'].min(),step=1.0)

    with col2:
        var6 = st.selectbox("Enter upload frequency",['Daily','Weekly','Every 2 Weeks', 'Monthly'  ])
        var7 = st.selectbox("Enter video quality",['4K','1080p','720p', '480p'])
        var8 = st.selectbox("Enter creator type",['multi-niche', 'lifestyle', 'general'])
        var9 = st.selectbox("Enter audience age group",['13-17', '18-24','25-34', '35+'])
        var10 = st.selectbox("Enter audience country",['Australia', 'Canada','India','United Kingdom','United States', ])


    predict_button=st.form_submit_button("Predict Subscribers")


if predict_button:
    input_data=pd.DataFrame(
            [
                {
                    'Monthly_Views':var1,
                    'Total_Videos':var2,
                    'Avg_Spend_Per_Video_USD':var3,
                    'Team_Members':var4,
                    'Avg_Video_Length_Min':var5,
                    'Upload_Frequency':var6,
                    'Video_Quality':var7,
                    'Creator_Type':var8,
                    'Audience_Age_Group':var9,
                    'Audience_Country':var10
                }
            ]
        )

    model=load_model()
    result=model.predict(input_data)[0]
    st.write(f":family_man_woman_girl_boy: Estimated Subscribers:   {result:.2f}")


